#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""أداة تشغيل بوابة الزبائن على الـVPS (مثبّتة كـ ops/web-portal.py). لا تلمس أي شي خارج: مخطط web، الدور web_rt، حاوية central-stg-web-portal،
ملف web_portal/web.env، وبلوك محدّد (BEGIN/END web-portal) بـCaddyfile. لا تلمس الحاويات ولا العملاء الحاليين.
  install            : هجرة 81 + دور web_rt + بناء الصورة + تشغيل الحاوية + بلوك Caddy (validate+reload مع رجوع تلقائي) + فحوصات
  status             : الحاوية، /healthz، بلوك Caddy، عدد المستخدمين
  invite --slug S --email E [--hours 72] : يطبع رابط دعوة لمرة وحدة (الرمز ما ينخزّن، فقط هاشه)
  down               : يوقف ويحذف الحاوية ويشيل بلوك Caddy (البيانات تبقى؛ التراجع الكامل بـ81_web_portal_down.sql يدوياً)"""
import argparse, hashlib, os, re, secrets, socket, subprocess, sys, time

ROOT = os.environ.get("WEB_ROOT", "/opt/central/web_portal")
CF = os.environ.get("WEB_CADDYFILE", "/opt/central/deploy/Caddyfile")
PG = os.environ.get("WEB_PG_CONTAINER", "central-stg-pg")
CADDY = os.environ.get("WEB_CADDY_CONTAINER", "central-stg-caddy")
NAME, IMAGE, ALIAS, PORT = "central-stg-web-portal", "central-web-portal:1", "web-portal", 8090
HOST = os.environ.get("WEB_HOST", "app.mohammedai.tech")
ENV = os.path.join(ROOT, "web.env")
BEGIN = "# BEGIN web-portal (generated by ops/web-portal.py — do not edit inside)"; END = "# END web-portal"
SLUG_RE = re.compile(r"[a-z0-9][a-z0-9-]{1,48}"); EMAIL_RE = re.compile(r"[^@\s'\"\;]{1,64}@[^@\s'\"\;]{1,60}\.[^@\s'\"\;]{2,20}")
HOST_RE = re.compile(r"[a-z0-9][a-z0-9.-]{3,80}")


class Fail(SystemExit):
    pass


def run(cmd, input=None, check=True, timeout=300):
    """نقطة التنفيذ الوحيدة (تُستبدل بالاختبارات). يرجّع (rc, stdout, stderr)"""
    r = subprocess.run(cmd, input=input, capture_output=True, text=True, timeout=timeout)
    if check and r.returncode:
        raise Fail("FAIL: %s -> %s" % (" ".join(cmd[:4]), (r.stderr or r.stdout).strip()[-300:]))
    return r.returncode, r.stdout, r.stderr


def psql(sql, v=None, check=True):
    cmd = ["docker", "exec", "-i", PG, "psql", "-U", "postgres", "-d", "central", "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1"]
    for k, val in (v or {}).items(): cmd += ["-v", "%s=%s" % (k, val)]
    return run(cmd + ["-f", "-"], input=sql, check=check)


def read_env():
    d = {}
    if os.path.exists(ENV):
        for l in open(ENV, encoding="utf-8").read().splitlines():
            if "=" in l and not l.startswith("#"): k, v = l.split("=", 1); d[k] = v
    return d


def write_env(d):
    tmp = ENV + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f: f.write("".join("%s=%s\n" % (k, v) for k, v in d.items()))
    os.replace(tmp, ENV); os.chmod(ENV, 0o600)


def network():
    _, out, _ = run(["docker", "inspect", PG, "--format", "{{range $k,$v := .NetworkSettings.Networks}}{{$k}} {{end}}"])
    nets = out.split()
    if not nets: raise Fail("FAIL: no docker network for " + PG)
    _, cout, _ = run(["docker", "inspect", CADDY, "--format", "{{range $k,$v := .NetworkSettings.Networks}}{{$k}} {{end}}"])
    common = [n for n in nets if n in cout.split()]
    if not common: raise Fail("FAIL: %s and %s share no docker network (found %s / %s)" % (PG, CADDY, nets, cout.split()))
    return common[0]


def caddy_block(host=HOST):
    return "\n".join([BEGIN, host + " {", "\tencode zstd gzip", "\treverse_proxy %s:%d" % (ALIAS, PORT), "}", END])


def update_caddyfile(text, remove=False, host=HOST):
    has_b, has_e = BEGIN in text, END in text
    if has_b != has_e: raise Fail("FAIL: web-portal markers in Caddyfile are incomplete; not editing")
    if has_b:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        head, tail = text[:a].rstrip("\n"), text[b:].lstrip("\n")
        mid = "\n" if remove else "\n\n" + caddy_block(host) + "\n"
        return head + mid + (("\n" + tail) if tail else "")
    return text if remove else text.rstrip("\n") + "\n\n" + caddy_block(host) + "\n"


def write_inplace(path, text):
    with open(path, "r+", encoding="utf-8") as f: f.seek(0); f.write(text); f.truncate()    # نفس الـinode حتى الـbind mount يشوف التعديل


def apply_caddy(remove=False, out=print):
    old = open(CF, encoding="utf-8").read(); new = update_caddyfile(old, remove)
    if new == old: out("Caddyfile ما يحتاج تغيير."); return False
    open(CF + ".preweb", "w", encoding="utf-8").write(old); write_inplace(CF, new)
    base = ["docker", "exec", CADDY, "caddy"]; tail = ["--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"]
    rc, _, err = run(base + ["validate"] + tail, check=False)
    if rc: write_inplace(CF, old); raise Fail("FAIL: caddy validate failed, Caddyfile restored: " + err[-300:])
    rc, _, err = run(base + ["reload"] + tail, check=False)
    if rc:
        write_inplace(CF, old); run(base + ["reload"] + tail, check=False); raise Fail("FAIL: caddy reload failed, Caddyfile restored: " + err[-300:])
    out("✅ Caddy حمّل الإعدادات (validate + reload)."); return True


def healthy(seconds=40):
    code = "import urllib.request,sys;sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:%d/healthz',timeout=3).status==200 else 1)" % PORT
    for _ in range(max(1, seconds // 2)):
        rc, _, _ = run(["docker", "exec", NAME, "python", "-c", code], check=False)
        if rc == 0: return True
        time.sleep(2)
    return False


def start_container():
    run(["docker", "rm", "-f", NAME], check=False)
    run(["docker", "run", "-d", "--name", NAME, "--network", network(), "--network-alias", ALIAS, "--restart", "unless-stopped", "--read-only", "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
         "--memory", "256m", "--cpus", "0.5", "--pids-limit", "128", "--tmpfs", "/tmp", "--env-file", ENV, IMAGE])


def cmd_install(a, out=print):
    if not HOST_RE.fullmatch(HOST): raise Fail("FAIL: bad host")
    for f in ("Dockerfile", "service/app.py", "db/81_web_portal.sql"):
        if not os.path.exists(os.path.join(ROOT, f)): raise Fail("FAIL: missing %s (install the package first)" % f)
    try: out("DNS: %s -> %s" % (HOST, socket.gethostbyname(HOST)))
    except Exception: out("⚠️ DNS: %s ما ينحل بعد (سجل A لازم يشير للسيرفر)" % HOST)
    out("1) الهجرة 81 ..."); psql(open(os.path.join(ROOT, "db/81_web_portal.sql"), encoding="utf-8").read())
    env = read_env()
    if not env.get("WEB_DB_DSN"):
        pw = secrets.token_urlsafe(32)
        psql("ALTER ROLE web_rt LOGIN PASSWORD '%s';\n" % pw)
        env = {"WEB_DB_DSN": "postgresql://web_rt:%s@%s:5432/central" % (pw, PG), "WEB_PORT": str(PORT), "WEB_COOKIE_SECURE": "1"}
        write_env(env); out("2) دور web_rt: كلمة سر جديدة انكتبت بـweb.env (600).")
    else: out("2) web.env موجود؛ أعدت استعماله.")
    out("3) بناء الصورة ..."); run(["docker", "build", "-t", IMAGE, "-f", os.path.join(ROOT, "Dockerfile"), ROOT], timeout=600)
    out("4) تشغيل الحاوية ..."); start_container()
    if not healthy():
        _, lo, le = run(["docker", "logs", "--tail", "6", NAME], check=False)
        raise Fail("FAIL: container not healthy (غالباً دخول قاعدة البيانات للدور web_rt مرفوض أو pg_hba). آخر السطور: " + (lo + le).strip()[-300:].replace("\n", " | "))
    out("✅ الحاوية سليمة (/healthz).")
    out("5) Caddy ..."); apply_caddy(False, out)
    rc, o, _ = psql("SELECT slug FROM core.tenants WHERE status::text = 'READY' ORDER BY slug LIMIT 1;", check=False)
    slug = o.strip().splitlines()[0] if rc == 0 and o.strip() else ""
    if slug:
        rc, o, e = psql("SELECT tenant_id::text AS t FROM core.tenants WHERE slug = :'slug' \\gset\nSET ROLE app_owner;\nSELECT count(*) FROM api.list_ad_accounts(private.sign_ctx(jsonb_build_object('t', :'t'::uuid, 'r', 'system', "
                        "'e', extract(epoch FROM now())::bigint + 300, 'k', 'system')));", {"slug": slug}, check=False)
        out("6) فحص شكل الـctx (قراءة فقط على %s، بصلاحية app_owner مثل دوال الموقع): %s" % (slug, "✅ مقبول (حسابات=%s)" % o.strip() if rc == 0 else "❌ مرفوض: " + " ".join((e or o).strip().splitlines()[:2])[:260]))
    out("انتهى. جرّب: https://%s/login (الشهادة قد تحتاج دقيقة). الدعوة: python3 ops/web-portal.py invite --slug <slug> --email <email>" % HOST)


def cmd_status(a, out=print):
    rc, o, _ = run(["docker", "inspect", NAME, "--format", "{{.State.Status}}"], check=False)
    out("container: %s" % (o.strip() if rc == 0 else "غير موجود"))
    out("healthz: %s" % ("OK" if rc == 0 and healthy(2) else "no"))
    out("caddy block: %s" % ("موجود" if BEGIN in open(CF, encoding="utf-8").read() else "غير موجود"))
    rc, o, _ = psql("SELECT count(*) || ' users, ' || (SELECT count(*) FROM web.sessions) || ' sessions' FROM web.users;", check=False)
    out("db: %s" % (o.strip() if rc == 0 else "الهجرة غير مطبّقة"))


def cmd_invite(a, out=print):
    if not SLUG_RE.fullmatch(a.slug or ""): raise Fail("FAIL: bad slug")
    if not EMAIL_RE.fullmatch(a.email or ""): raise Fail("FAIL: bad email")
    if not 1 <= a.hours <= 168: raise Fail("FAIL: hours must be 1..168")
    tok = secrets.token_hex(16); h = hashlib.sha256(tok.encode()).hexdigest()   # أرقام وحروف إنكليزية صغيرة فقط: أسهل بالنسخ
    rc, o, e = psql("SELECT web.invite_create(:'slug', :'email', :'h', :hours);", {"slug": a.slug, "email": a.email, "h": h, "hours": str(a.hours)}, check=False)
    if rc: raise Fail("FAIL: " + (e or o).strip()[-250:])
    out("✅ الدعوة جاهزة لمدة %d ساعة، لمرة وحدة. ابعثها للزبون (واتساب) ولا تنشرها:" % a.hours); out("https://%s/invite/%s" % (HOST, tok)); out("مرجع الدعوة (للتشخيص فقط، مو سر): %s" % h[:8])


def cmd_down(a, out=print):
    run(["docker", "rm", "-f", NAME], check=False); apply_caddy(True, out); out("الحاوية والبلوك انحذفوا. البيانات بقت بالقاعدة.")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter); s = p.add_subparsers(dest="cmd", required=True)
    s.add_parser("install"); s.add_parser("status"); s.add_parser("down")
    i = s.add_parser("invite"); i.add_argument("--slug", required=True); i.add_argument("--email", required=True); i.add_argument("--hours", type=int, default=72)
    a = p.parse_args(argv); {"install": cmd_install, "status": cmd_status, "invite": cmd_invite, "down": cmd_down}[a.cmd](a)


if __name__ == "__main__":
    main()
