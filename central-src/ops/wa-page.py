#!/usr/bin/env python3
"""صفحات هبوط واتساب على دومين مستقل (لإعلانات سناب اللي ترفض رابط wa.me مباشرة).
كل صفحة: عنوان + نص + رقم ظاهر + زر «تواصل عبر واتساب» (يفتح wa.me برسالة جاهزة). بدون تحويل تلقائي.
تُحقن كبلوك ثابت بـCaddyfile (نفس طريقة /tiktok-code): كتابة بنفس الملف (حتى ما ينكسر الـbind mount) ثم caddy validate ثم reload،
وعند فشل التحقق يرجع الملف القديم تلقائياً. السجل (بدون أسرار) بـdeploy/wa-pages.json.
الاستعمال من /opt/central:
  python3 ops/wa-page.py add --slug CLIENT --phone 07XXXXXXXXX --business "اسم النشاط" [--title ...] [--desc ...] [--text "رسالة جاهزة"]
  python3 ops/wa-page.py list | remove CODE | show CODE      (متغير WA_DOMAIN، الافتراضي wa.twasuliraq.com؛ alias «www.» يُضاف فقط للدومين الجذر)"""
import argparse, html, json, os, random, re, socket, subprocess, sys, time, urllib.parse

BASE = os.environ.get("WA_BASE", "/opt/central/")
DOMAIN = os.environ.get("WA_DOMAIN", "wa.twasuliraq.com").strip().lower()
CADDY = os.environ.get("WA_CADDY_CONTAINER", "central-stg-caddy")
CF = BASE + "deploy/Caddyfile"; REG = BASE + "deploy/wa-pages.json"
BEGIN = "# BEGIN wa-pages (generated by ops/wa-page.py — do not edit inside)"; END = "# END wa-pages"
ALPHA = "abcdefghjkmnpqrstuvwxyz23456789"


class Fail(Exception):
    pass


def clean(s, n=200):
    """نص آمن لـCaddy (بدون أقواس {} ولا backtick) وللـHTML."""
    s = re.sub(r"[`{}$\\\x00-\x1f]", " ", str(s or "")); s = re.sub(r"\s+", " ", s).strip()[:n]
    return s


def norm_phone(p):
    d = re.sub(r"\D", "", str(p or ""))
    if d.startswith("00"): d = d[2:]
    if d.startswith("07") and len(d) == 11: d = "964" + d[1:]       # عراقي محلي 07xxxxxxxxx
    if d.startswith("7") and len(d) == 10: d = "964" + d
    if not re.fullmatch(r"[1-9][0-9]{7,14}", d): raise Fail("رقم الواتساب غير صالح: اكتبه مثل 07701234567 أو 9647701234567")
    return d


def wa_url(phone, text):
    u = "https://wa.me/" + phone
    return u + ("?text=" + urllib.parse.quote(text) if text else "")


def render_page(link):
    e = lambda s: html.escape(s, quote=True)
    biz, title, desc, phone = e(link["business"]), e(link["title"]), e(link["desc"]), link["phone"]
    return ('<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1"><title>' + title + '</title><link rel="icon" href="data:,"></head>'
            '<body style="margin:0;background:#f5f7fa;font-family:Tahoma,Arial,sans-serif;color:#1c2b36">'
            '<div style="max-width:520px;margin:0 auto;padding:28px 18px;text-align:center">'
            '<h1 style="font-size:26px;margin:18px 0 8px">' + biz + '</h1>'
            '<p style="font-size:18px;line-height:1.7;margin:0 0 22px">' + desc + '</p>'
            '<a href="' + e(wa_url(phone, link["text"])) + '" style="display:block;background:#25d366;color:#fff;text-decoration:none;font-size:20px;font-weight:bold;padding:16px;border-radius:12px">تواصل معنا عبر واتساب</a>'
            '<p style="font-size:15px;color:#51606b;margin:18px 0 0">رقم التواصل: <span dir="ltr">+' + phone + '</span></p>'
            '<p style="font-size:13px;color:#8a97a1;margin:26px 0 0">نرد على رسائلك بأقرب وقت.</p>'
            '</div></body></html>')


def build_block(links):
    hosts = DOMAIN + (", www." + DOMAIN if DOMAIN.count(".") == 1 else "")     # www فقط للدومين الجذر (مثل twasuliraq.com)
    out = [BEGIN, hosts + " {", "\tencode zstd gzip",
           "\theader {", '\t\tStrict-Transport-Security "max-age=31536000"', "\t\tX-Content-Type-Options nosniff", "\t\t-Server", "\t}"]
    for l in links:
        out += ["\thandle /w/%s {" % l["code"], '\t\theader Content-Type "text/html; charset=utf-8"', '\t\theader Cache-Control "public, max-age=300"',
                "\t\trespond `" + render_page(l) + "` 200", "\t}"]
    out += ["\thandle {", '\t\trespond "" 404', "\t}", "}", END]
    return "\n".join(out)


def update_caddyfile(text, links):
    block = build_block(links)
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    if BEGIN in text or END in text: raise Fail("علامات wa-pages بـCaddyfile ناقصة؛ ما أعدّل.")
    return text.rstrip("\n") + "\n\n" + block + "\n"


def write_inplace(path, text):
    with open(path, "r+", encoding="utf-8") as f:     # بنفس الـinode حتى الـbind mount يشوف التعديل
        f.seek(0); f.write(text); f.truncate()


def sh(args, timeout=60):
    r = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    return r.returncode, (r.stdout + r.stderr).strip()


def apply_links(links, runner=sh, out=print):
    with open(CF, encoding="utf-8") as f: old = f.read()
    new = update_caddyfile(old, links)
    if new == old: out("لا تغيير بـCaddyfile."); return True
    with open(CF + ".prewa", "w", encoding="utf-8") as f: f.write(old)
    write_inplace(CF, new)
    rc, msg = runner(["docker", "exec", CADDY, "caddy", "validate", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"])
    if rc:
        write_inplace(CF, old); raise Fail("caddy validate فشل، رجّعت Caddyfile القديم. الخطأ: " + msg[-300:])
    rc, msg = runner(["docker", "exec", CADDY, "caddy", "reload", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"])
    if rc:
        write_inplace(CF, old); runner(["docker", "exec", CADDY, "caddy", "reload", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"])
        raise Fail("caddy reload فشل، رجّعت Caddyfile القديم. الخطأ: " + msg[-300:])
    out("✅ Caddy حمّل الإعدادات (validate + reload).")
    return True


def load_reg():
    try:
        with open(REG, encoding="utf-8") as f: return json.load(f)
    except FileNotFoundError: return []


def save_reg(links):
    tmp = REG + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f: json.dump(links, f, ensure_ascii=False, indent=1)
    os.replace(tmp, REG)


def new_code(existing):
    while True:
        c = "".join(random.choice(ALPHA) for _ in range(8))
        if c not in existing: return c


def cmd_add(a, runner=sh, out=print):
    slug = a.slug.strip()
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,48}", slug): raise Fail("slug غير صالح.")
    phone = norm_phone(a.phone); biz = clean(a.business, 60)
    if not biz: raise Fail("اسم النشاط مطلوب (--business).")
    links = load_reg(); code = new_code({l["code"] for l in links})
    link = {"code": code, "slug": slug, "phone": phone, "business": biz, "title": clean(a.title or biz, 80), "desc": clean(a.desc or ("للطلب والاستفسار تواصل معنا مباشرة عبر واتساب."), 160),
            "text": clean(a.text or "", 160), "created": time.strftime("%Y-%m-%d %H:%M:%S")}
    links.append(link); apply_links(links, runner, out); save_reg(links)
    url = "https://%s/w/%s" % (DOMAIN, code)
    out("الرابط: " + url); out("العميل: %s | الرقم: +%s | النشاط: %s" % (slug, phone, biz))
    try:
        ip = socket.gethostbyname(DOMAIN); out("DNS للدومين يشير إلى: " + ip + " (تأكد أنه IP السيرفر)")
    except Exception: out("⚠️ الدومين ما يحلّ DNS بعد؛ أضف سجل A إلى IP السيرفر وانتظر الانتشار، ثم افتح الرابط.")
    return url


def cmd_remove(a, runner=sh, out=print):
    links = load_reg(); keep = [l for l in links if l["code"] != a.code]
    if len(keep) == len(links): raise Fail("ما لقيت هذا الكود.")
    apply_links(keep, runner, out); save_reg(keep); out("انحذفت الصفحة %s." % a.code)


def main(argv=None):
    ap = argparse.ArgumentParser(); sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("add")
    for k in ("slug", "phone", "business"): p.add_argument("--" + k, required=True)
    for k in ("title", "desc", "text"): p.add_argument("--" + k, default="")
    sp.add_parser("list"); sp.add_parser("remove").add_argument("code"); sp.add_parser("show").add_argument("code")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "add": cmd_add(a)
        elif a.cmd == "remove": cmd_remove(a)
        elif a.cmd == "list":
            for l in load_reg(): print("%s | %s | +%s | %s | https://%s/w/%s" % (l["code"], l["slug"], l["phone"], l["business"], DOMAIN, l["code"]))
        else:
            for l in load_reg():
                if l["code"] == a.code: print(json.dumps(l, ensure_ascii=False, indent=1)); return 0
            raise Fail("ما لقيت هذا الكود.")
    except Fail as e:
        print("⛔ " + str(e)); return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
