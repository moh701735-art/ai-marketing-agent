"""قوائم كلمات (عربي/لهجة عراقية/إنكليزي) لتصنيف حتمي — بدون LLM. النص يُطبَّع قبل المطابقة (أإآ→ا، ة→ه، ى→ي، تشكيل، أرقام عربية)."""
import re

_AR_DIG = {0x0660 + i: ord(str(i)) for i in range(10)}


def norm(s: str) -> str:
    s = re.sub(r"[ً-ٟـ]", "", str(s or "")).translate(_AR_DIG).lower()
    for a, b in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ة", "ه"), ("ى", "ي")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s)


